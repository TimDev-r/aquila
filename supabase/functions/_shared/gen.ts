// Regenerates files derived from other sources. Run from the repo root:
//   deno run --no-lock --allow-read --allow-write supabase/functions/_shared/gen.ts
// - _shared/fallbackQuestions.ts from src/content/lessons.json (Person 4)
// - prompts/*.md from _shared/prompts.ts
import type { Lesson, QuizQuestion } from "./contracts.ts";
import { promptDocs } from "./promptDocs.ts";

const here = new URL(".", import.meta.url);
const root = new URL("../../../", import.meta.url);

const { lessons } = JSON.parse(await Deno.readTextFile(new URL("src/content/lessons.json", root))) as {
  lessons: Lesson[];
};
const questions: QuizQuestion[] = lessons
  .toSorted((a, b) => a.order - b.order)
  .flatMap((l) => l.questions)
  .map(({ id, question, options, correctIndex, explanation, tag }) => ({
    id, question, options, correctIndex, explanation, tag,
  }));
await Deno.writeTextFile(
  new URL("fallbackQuestions.ts", here),
  `// GENERATED by _shared/gen.ts from src/content/lessons.json. Do not edit by hand.\n` +
    `import type { QuizQuestion } from "./contracts.ts";\n\n` +
    `export const FALLBACK_QUESTIONS: QuizQuestion[] = ${JSON.stringify(questions, null, 2)};\n`,
);
console.log(`fallbackQuestions.ts: ${questions.length} questions from ${lessons.length} lessons`);

for (const doc of promptDocs()) {
  await Deno.writeTextFile(new URL(`prompts/${doc.file}`, root), doc.markdown);
  console.log(`prompts/${doc.file}`);
}
